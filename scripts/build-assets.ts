// Build-time asset preparation: the engagement photos live in
// media/images/engagement/ at their served size — resized in place (height
// 1000px; 2961.jpg at width 2000px; 2894.jpg cropped to its bottom half),
// and the luma logo in media/images/luma/ at width 600px — so the build
// no longer resizes anything and there is no generated/ folder. The
// stylesheets reference the photos via plain url() and Vite bundles +
// content-hashes them: the detail ::before rules and the gallery thumbnail
// rules in css/engagement-photos.scss both reference the same url(), so
// each photo is emitted once and shared. The only generated file is
// css/engagement-photo-ids.scss: the folder-derived id list the stylesheet
// iterates, so the list can never drift from the folder. The per-photo
// settings (zoom/shift) stay hand-kept in the stylesheet; only two photos
// have any.
import { readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const ROOT = path.resolve(import.meta.dirname, '..');
const ENGAGEMENT_DIR = path.join(ROOT, 'media/images/engagement');
const IDS_FILE = path.join(ROOT, 'css', 'engagement-photo-ids.scss');

// Write css/engagement-photo-ids.scss: the sorted list of photo ids, so
// css/engagement-photos.scss iterates the folder contents instead of a
// hand-kept list — a photo added to or removed from the folder appears in
// (or disappears from) both the gallery and the CSS with no list edit, and
// drift is impossible. Returns the sorted engagement filenames, so the
// plugin can inject the gallery <li>s in the same order the old manifest
// build used.
export async function prepareAssets(): Promise<string[]> {
    const engagementFiles = (await readdir(ENGAGEMENT_DIR))
        .filter((file) => file.endsWith('.jpg'))
        .sort();

    const engagementIds = engagementFiles.map((file) => file.slice(0, -'.jpg'.length));
    await writeFile(
        IDS_FILE,
        `// Generated by scripts/build-assets.ts from media/images/engagement — do not edit by hand.\n$engagement-photo-ids: (${engagementIds.map((id) => `"${id}"`).join(', ')});\n`,
    );

    return engagementFiles;
}
